#!/usr/bin/env node
/**
 * Reads SUPABASE_URL and SUPABASE_ANON_KEY from .env and writes assets/supabaseConfig.js.
 * Run after cloning or when .env changes: npm run sync:config
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = join(root, '.env');
const outPath = join(root, 'assets', 'supabaseConfig.js');

function parseEnv(text) {
  const env = {};
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    env[key] = val;
  }
  return env;
}

if (!existsSync(envPath)) {
  console.error('Missing .env — copy .env.example and add SUPABASE_URL + SUPABASE_ANON_KEY');
  process.exit(1);
}

const env = parseEnv(readFileSync(envPath, 'utf8'));
const url = env.SUPABASE_URL?.trim();
const key = env.SUPABASE_ANON_KEY?.trim();

if (!url || !key) {
  console.error('.env must define SUPABASE_URL and SUPABASE_ANON_KEY');
  process.exit(1);
}

const content = `// Auto-generated by scripts/sync-supabase-config.mjs — do not edit by hand
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(key)};
`;

writeFileSync(outPath, content, 'utf8');
console.log(`Wrote ${outPath}`);
